def fill_sections(path:Path, sections:dict[str,str]):
    original=path.read_text(encoding="utf-8")
    seen=set()
    pattern=r"(?ms)^(## ([^\n]+)\n)(.*?)(?=^## |\Z)"
    def substitute(match):
        title=match.group(2).strip()
        if title not in sections:
            return match.group(0)
        seen.add(title)
        return match.group(1)+"\n"+sections[title].strip()+"\n\n"
    result=re.sub(pattern,substitute,original)
    missing=set(sections)-seen
    if missing:
        raise ValueError(f"{path}: missing sections: {sorted(missing)}")
    if "<!-- REQUIRED:" in result:
        raise ValueError(f"{path}: unresolved REQUIRED marker")
    path.write_text(result,encoding="utf-8")

